export function getElementById(symbol: string): Element | undefined {
  return ELEMENTS.find((e) => e.symbol === symbol);
}

export function getElementByAtomicNumber(n: number): Element | undefined {
  return ELEMENTS.find((e) => e.atomicNumber === n);
}

export function searchElements(query: string): Element[] {
  const q = query.toLowerCase().trim();
  if (!q) return ELEMENTS;
  return ELEMENTS.filter(
    (e) =>
      e.name.toLowerCase().includes(q) ||
      e.symbol.toLowerCase().includes(q) ||
      String(e.atomicNumber).includes(q) ||
      e.category.includes(q),
  );
}

export function getElementsByCategory(category: ElementCategory): Element[] {
  return ELEMENTS.filter((e) => e.category === category);
}
